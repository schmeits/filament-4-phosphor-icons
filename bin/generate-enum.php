<?php

declare(strict_types=1);

/*
 * bin/generate-enum.php
 *
 * Generates src/Support/Icons/Phosphor.php from the SVG files of the installed
 * codeat3/blade-phosphor-icons package. Run it after upgrading that package:
 *
 *     composer generate-enum
 *     php bin/generate-enum.php --output=/tmp/Phosphor.php
 *
 * The output only depends on the installed upstream version, so running it
 * twice against the same vendor directory gives an identical file.
 */

$root = dirname(__DIR__);
$upstream = 'codeat3/blade-phosphor-icons';
$svgDir = $root . '/vendor/' . $upstream . '/resources/svg';
$enumFile = $root . '/src/Support/Icons/Phosphor.php';

foreach (array_slice($argv, 1) as $argument) {
    if (str_starts_with($argument, '--output=')) {
        $enumFile = substr($argument, strlen('--output='));
    }
}

if (! is_dir($svgDir)) {
    fwrite(STDERR, "SVG directory not found: {$svgDir}\n");
    exit(1);
}

/**
 * The installed version and release date of the icon source, read from
 * Composer's installed.json so the generated file records where it came from.
 *
 * @return array{version: string, date: string}
 */
function upstreamRelease(string $root, string $package): array
{
    $installed = json_decode((string) file_get_contents($root . '/vendor/composer/installed.json'), true);
    $packages = is_array($installed) && is_array($installed['packages'] ?? null) ? $installed['packages'] : [];

    foreach ($packages as $entry) {
        if (! is_array($entry) || ($entry['name'] ?? null) !== $package) {
            continue;
        }

        $version = is_string($entry['version'] ?? null) ? $entry['version'] : 'unknown';
        $time = is_string($entry['time'] ?? null) ? $entry['time'] : 'unknown';

        return ['version' => ltrim($version, 'v'), 'date' => substr($time, 0, 10)];
    }

    return ['version' => 'unknown', 'date' => 'unknown'];
}

// Every weight except regular ships as "<name>-<weight>.svg". Only the regular
// file (without suffix) counts as a unique icon.
$weightSuffixes = ['-fill', '-light', '-thin', '-duotone', '-regular', '-bold'];

$enumCases = [];

foreach (scandir($svgDir) ?: [] as $file) {
    if (preg_match('/^(.*)\.svg$/', $file, $matches) !== 1) {
        continue;
    }

    $iconName = $matches[1];

    foreach ($weightSuffixes as $suffix) {
        if (str_ends_with($iconName, $suffix)) {
            continue 2;
        }
    }

    $enumKey = str_replace(' ', '', ucwords(str_replace(['-', '_'], ' ', $iconName)));

    // An enum case cannot start with a digit.
    if (preg_match('/^\d/', $enumKey) === 1) {
        $enumKey = '_' . $enumKey;
    }

    $enumCases[] = "    case {$enumKey} = '{$iconName}';";
}

$release = upstreamRelease($root, $upstream);

$enumContent = <<<PHP
<?php

declare(strict_types=1);

/*
 * src/Support/Icons/Phosphor.php
 *
 * Every Phosphor icon as a backed enum that Filament can scale. Do not edit
 * by hand: this file is generated by bin/generate-enum.php.
 *
 * Generated from {$upstream} {$release['version']} (released {$release['date']}).
 */

namespace Schmeits\\FilamentPhosphorIcons\\Support\\Icons;

use Filament\\Support\\Contracts\\ScalableIcon;
use Filament\\Support\\Enums\\IconSize;

enum Phosphor: string implements ScalableIcon
{
%CASES%

    public function getIconForSize(IconSize \$size): string
    {
        return match (\$size) {
            IconSize::ExtraSmall, IconSize::Small => "phosphor-{\$this->value}-thin",
            IconSize::Medium => "phosphor-{\$this->value}",
            IconSize::Large, IconSize::ExtraLarge, IconSize::TwoExtraLarge => "phosphor-{\$this->value}-bold",
        };
    }

    public function getIconForWeight(PhosphorWeight \$weight): string
    {
        if (\$weight === PhosphorWeight::Regular) {
            return "phosphor-{\$this->value}";
        }

        return "phosphor-{\$this->value}-{\$weight->value}";
    }
}

PHP;

file_put_contents($enumFile, str_replace('%CASES%', implode("\n", $enumCases), $enumContent));

echo 'Phosphor enum generated with ' . count($enumCases) . " icons from {$upstream} {$release['version']}.\n";
